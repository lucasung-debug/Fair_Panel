import React from 'react';
import {
  FileText,
  CheckCircle2,
  AlertTriangle,
  Scale,
  Sparkles,
  BarChart3,
  ShieldCheck,
  RefreshCw,
} from 'lucide-react';
import { AuditReport as AuditReportType } from '../types';
import { LAW_MAP } from '../data/laws';

interface AuditReportProps {
  report: AuditReportType | null;
  isLoading: boolean;
  onRefreshReport: () => void;
}

export const AuditReport: React.FC<AuditReportProps> = ({
  report,
  isLoading,
  onRefreshReport,
}) => {
  if (isLoading && !report) {
    return (
      <div className="bg-white border border-slate-200 rounded-xl p-12 text-center space-y-4">
        <RefreshCw className="w-8 h-8 text-indigo-950 animate-spin mx-auto" />
        <h3 className="text-base font-bold text-slate-900 font-display">
          Synthesizing Post-Interview Executive Audit Report...
        </h3>
        <p className="text-xs text-slate-600 max-w-md mx-auto">
          Calling Gemini 4 Argon with high reasoning depth to audit statutory compliance, intercepted risk logs, and rubric rationale validity.
        </p>
      </div>
    );
  }

  if (!report) {
    return (
      <div className="bg-white border border-slate-200 rounded-xl p-12 text-center space-y-4">
        <FileText className="w-8 h-8 text-slate-400 mx-auto" />
        <h3 className="text-base font-bold text-slate-900 font-display">
          No Audit Report Generated Yet
        </h3>
        <p className="text-xs text-slate-600 max-w-md mx-auto">
          Conduct interview turns or generate a simulated compliance audit to produce the executive evaluation report.
        </p>
        <button
          type="button"
          onClick={onRefreshReport}
          className="inline-flex items-center gap-1.5 px-4 py-2 text-xs font-semibold text-white bg-indigo-950 rounded-lg hover:bg-indigo-900 transition-colors"
        >
          <Sparkles className="w-3.5 h-3.5" />
          Generate Post-Interview Audit Report (Gemini 4 Argon)
        </button>
      </div>
    );
  }

  return (
    <div className="space-y-6">
      {/* Executive Summary Card */}
      <div className="bg-white border border-slate-200 rounded-xl p-6 space-y-4">
        <div className="flex flex-wrap items-center justify-between gap-4 border-b border-slate-200 pb-4">
          <div>
            <div className="flex items-center gap-2">
              <span className="text-xs font-bold uppercase tracking-tight text-indigo-950 bg-indigo-50 border border-indigo-200 px-2.5 py-0.5 rounded">
                Executive Compliance &amp; Competency Audit
              </span>
              <span className="text-xs font-mono text-slate-500">
                Generated by: {report.generatedByModel || 'gemini-4-argon'}
              </span>
            </div>
            <h2 className="text-lg font-bold text-slate-950 font-display mt-1">
              Interview Process Governance &amp; Fairness Audit Report
            </h2>
          </div>
          <button
            type="button"
            onClick={onRefreshReport}
            disabled={isLoading}
            className="inline-flex items-center gap-1.5 px-3.5 py-2 text-xs font-semibold text-slate-800 bg-white border border-slate-300 rounded-lg hover:bg-slate-100 disabled:opacity-50 transition-colors shrink-0"
          >
            <RefreshCw className={`w-3.5 h-3.5 ${isLoading ? 'animate-spin' : ''}`} />
            {isLoading ? 'Re-synthesizing...' : 'Re-synthesize Audit'}
          </button>
        </div>

        <p className="text-sm text-slate-700 leading-relaxed font-medium">
          {report.summary}
        </p>

        {/* Top KPI Metrics Grid */}
        <div className="grid grid-cols-1 md:grid-cols-3 gap-4 pt-2">
          <div className="bg-slate-50 border border-slate-200 rounded-lg p-4">
            <div className="text-xs font-semibold text-slate-600 flex items-center gap-1.5">
              <ShieldCheck className="w-4 h-4 text-emerald-700" />
              HR Standard Question Compliance
            </div>
            <div className="text-2xl font-bold text-slate-950 mt-1 tabular-nums font-display">
              {report.hrStandardCompliance.complianceRate}%
            </div>
            <div className="text-[11px] text-slate-500 mt-0.5">
              {report.hrStandardCompliance.completedMandatory} of{' '}
              {report.hrStandardCompliance.totalMandatory} mandatory questions asked
            </div>
          </div>

          <div className="bg-slate-50 border border-slate-200 rounded-lg p-4">
            <div className="text-xs font-semibold text-slate-600 flex items-center gap-1.5">
              <BarChart3 className="w-4 h-4 text-indigo-950" />
              Competency Verification Coverage
            </div>
            <div className="text-2xl font-bold text-slate-950 mt-1 tabular-nums font-display">
              {report.coverage.filter((c) => c.asked).length} / {report.coverage.length}
            </div>
            <div className="text-[11px] text-slate-500 mt-0.5">
              Core JD competencies verified with behavioral turns
            </div>
          </div>

          <div className="bg-slate-50 border border-slate-200 rounded-lg p-4">
            <div className="text-xs font-semibold text-slate-600 flex items-center gap-1.5">
              <Scale className="w-4 h-4 text-rose-700" />
              Intercepted Pre-Ask Risks
            </div>
            <div className="text-2xl font-bold text-slate-950 mt-1 tabular-nums font-display">
              {report.interceptedRisks.length} Interceptions
            </div>
            <div className="text-[11px] text-slate-500 mt-0.5">
              Zero statutory violations reached the candidate
            </div>
          </div>
        </div>
      </div>

      {/* Competency Coverage Table */}
      <div className="bg-white border border-slate-200 rounded-xl p-6 space-y-4">
        <h3 className="text-base font-bold text-slate-950 font-display flex items-center gap-2">
          <span>1. Core Competency Verification Matrix</span>
        </h3>
        <div className="border border-slate-200 rounded-lg overflow-hidden">
          <table className="w-full text-left border-collapse text-xs">
            <thead>
              <tr className="bg-slate-100 border-b border-slate-200 text-slate-700 font-semibold">
                <th className="py-2.5 px-3 w-16 text-center">ID</th>
                <th className="py-2.5 px-3">Competency Dimension</th>
                <th className="py-2.5 px-3 w-28 text-center">Verification Status</th>
                <th className="py-2.5 px-3 w-24 text-right">Turn Count</th>
              </tr>
            </thead>
            <tbody className="divide-y divide-slate-200">
              {report.coverage.map((comp) => (
                <tr key={comp.competencyId} className="hover:bg-slate-50/80">
                  <td className="py-2.5 px-3 text-center font-mono font-bold text-slate-600">
                    {comp.competencyId}
                  </td>
                  <td className="py-2.5 px-3 font-medium text-slate-900">
                    {comp.name}
                  </td>
                  <td className="py-2.5 px-3 text-center">
                    {comp.asked ? (
                      <span className="inline-flex items-center gap-1 px-2 py-0.5 rounded-full text-[11px] font-semibold bg-emerald-100 text-emerald-800">
                        <CheckCircle2 className="w-3 h-3" />
                        Verified
                      </span>
                    ) : (
                      <span className="inline-flex items-center gap-1 px-2 py-0.5 rounded-full text-[11px] font-semibold bg-amber-100 text-amber-800">
                        <AlertTriangle className="w-3 h-3" />
                        Pending
                      </span>
                    )}
                  </td>
                  <td className="py-2.5 px-3 text-right font-mono tabular-nums text-slate-700">
                    {comp.turnCount} turns
                  </td>
                </tr>
              ))}
            </tbody>
          </table>
        </div>
      </div>

      {/* Pre-Ask Intercepted Risk & Mitigation Log */}
      <div className="bg-white border border-slate-200 rounded-xl p-6 space-y-4">
        <h3 className="text-base font-bold text-slate-950 font-display flex items-center justify-between">
          <span>2. Pre-Ask Risk Interception &amp; Mitigation Audit</span>
          <span className="text-xs font-normal text-slate-500">
            {report.interceptedRisks.length} questions intercepted before candidate delivery
          </span>
        </h3>

        {report.interceptedRisks.length === 0 ? (
          <div className="p-4 bg-emerald-50/60 border border-emerald-200 rounded-lg text-xs text-emerald-900 font-medium">
            Clean Interview Record: No discriminatory or high-risk questions were drafted during this session.
          </div>
        ) : (
          <div className="space-y-3">
            {report.interceptedRisks.map((risk, idx) => {
              const lawNames = (risk.lawRefs || [])
                .map((id) => LAW_MAP[id]?.shortName || id)
                .join(' · ');

              return (
                <div
                  key={idx}
                  className="p-4 border rounded-lg bg-slate-50 border-slate-200 space-y-2 text-xs"
                >
                  <div className="flex flex-wrap items-center justify-between gap-2">
                    <span
                      className={`font-bold uppercase px-2 py-0.5 rounded text-[10px] ${
                        risk.level === 'high'
                          ? 'bg-rose-100 text-rose-800 border border-rose-200'
                          : 'bg-amber-100 text-amber-800 border border-amber-200'
                      }`}
                    >
                      {risk.level} Risk · {risk.categoryLabel}
                    </span>
                    <span className="font-medium text-slate-600">
                      Action: {risk.actionTaken}
                    </span>
                  </div>

                  <div className="text-rose-800">
                    <strong className="text-rose-950">Blocked Draft:</strong> &ldquo;
                    {risk.originalDraft}&rdquo;
                  </div>

                  {risk.alternativeUsed && (
                    <div className="text-emerald-800 font-medium bg-emerald-50/80 border border-emerald-200 p-2.5 rounded">
                      <strong className="text-emerald-950">Neutral Replacement:</strong> &ldquo;
                      {risk.alternativeUsed}&rdquo;
                    </div>
                  )}

                  {lawNames ? (
                    <div className="text-[11px] text-slate-600 pt-1 border-t border-slate-200">
                      <strong>Statutory Basis:</strong> {lawNames}
                    </div>
                  ) : (
                    <div className="text-[11px] text-slate-500 pt-1 border-t border-slate-200">
                      Job-Irrelevant Private Life · No Direct Statutory Match (lawRefs: [])
                    </div>
                  )}
                </div>
              );
            })}
          </div>
        )}
      </div>

      {/* Rationale & Bias Evaluation Audit */}
      {report.evaluationAudit && report.evaluationAudit.length > 0 && (
        <div className="bg-white border border-slate-200 rounded-xl p-6 space-y-4">
          <h3 className="text-base font-bold text-slate-950 font-display">
            3. Evaluator Scoring Rationale Grounding Check
          </h3>
          <div className="space-y-3">
            {report.evaluationAudit.map((item, idx) => (
              <div
                key={idx}
                className="p-4 border border-slate-200 rounded-lg bg-slate-50 text-xs space-y-2"
              >
                <div className="flex items-center justify-between">
                  <span className="font-semibold text-slate-900">
                    Turn {item.turnIndex}: {item.question}
                  </span>
                  <span className="font-bold text-indigo-950">
                    Score: {item.score}/5
                  </span>
                </div>
                <div className="text-slate-700 bg-white p-2.5 rounded border border-slate-200">
                  <strong>Evaluator Rationale:</strong> &ldquo;{item.rationale}&rdquo;
                </div>
                <div
                  className={`p-2 rounded text-[11px] font-medium ${
                    item.isEvidenceGrounded
                      ? 'bg-emerald-50 text-emerald-900 border border-emerald-200'
                      : 'bg-rose-50 text-rose-900 border border-rose-200'
                  }`}
                >
                  {item.feedback}
                </div>
              </div>
            ))}
          </div>
        </div>
      )}

      {/* AI Recommendations */}
      {report.suggestions && report.suggestions.length > 0 && (
        <div className="bg-indigo-50/60 border border-indigo-200 rounded-xl p-6 space-y-3 text-xs">
          <h3 className="text-sm font-bold text-indigo-950 font-display flex items-center gap-1.5">
            <Sparkles className="w-4 h-4" />
            FairPanel Governance &amp; Continuous Improvement Recommendations
          </h3>
          <ul className="list-disc pl-5 space-y-1.5 text-indigo-950/90 leading-relaxed">
            {report.suggestions.map((sug, i) => (
              <li key={i}>{sug}</li>
            ))}
          </ul>
        </div>
      )}
    </div>
  );
};
